#!/usr/bin/env python3
"""Generate QE/Wannier inputs and the Fortran module from parameter; run no jobs."""
from pathlib import Path
import argparse
import hashlib
import math
from string import Template

from parameters import ROOT, fortran_module, load


def render(values: dict) -> dict[Path, str]:
    p = dict(values)
    p["structure"] = (ROOT / "1_scf/structure.in").read_text().strip()
    p["pseudo_dir"] = repr(p["pseudo_dir"])
    p["nk"] = p["nk1"] * p["nk2"] * p["nk3"]
    p["kpoints"] = "\n".join(
        f"{i/p['nk1']:.12f} {j/p['nk2']:.12f} {k/p['nk3']:.12f}"
        for k in range(p["nk3"]) for j in range(p["nk2"]) for i in range(p["nk1"]))
    p["weighted_kpoints"] = "\n".join(f"{line} {1/p['nk']:.16e}" for line in p["kpoints"].splitlines())
    a = p["a0"] * 0.529177210903
    p["unit_cell"] = f"{a:.12f} 0 0\n{-a/2:.12f} {math.sqrt(3)*a/2:.12f} 0\n0 0 {a*p['celldm3']:.12f}"
    outputs = {ROOT / ".build/parameter_mod.f90": fortran_module(values)}
    for stage in ("1_scf", "2_band", "3_band_no_mag", "5_wannier"):
        for source in (ROOT / stage).glob("*.template"):
            target = source.with_suffix("")
            if target.suffix == ".win":
                target = target.with_name(values["prefix"] + ".win")
            header = "#" if target.suffix == ".win" else "!"
            outputs[target] = (f"{header} Generated by configure.py from parameter; do not edit.\n"
                               + Template(source.read_text()).substitute(p))
    return outputs


def configure() -> None:
    values = load()
    outputs = render(values)
    for path in outputs:
        if path.exists() and not path.read_text().startswith(("! Generated", "# Generated")):
            raise FileExistsError(f"refusing to overwrite an unmanaged file: {path}")
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    # The fingerprint also catches edits to an alternate ANSATZ_PARAMETER file.
    fingerprint = hashlib.sha256(fortran_module(values).encode()).hexdigest()
    (ROOT / ".build/configuration.sha256").write_text(fingerprint + "\n")
    print(f"Generated {len(outputs)} files; no calculations or submissions performed.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate configuration and templates without writing")
    args = parser.parse_args()
    if args.check:
        render(load())
        print("PASS: parameter and all input templates")
    else:
        configure()
